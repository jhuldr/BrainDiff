from typing import Any, Generator
import numpy as np
import pandas as pd
import os
import time
from openai import OpenAI
from openai import (
    APIConnectionError,
    APITimeoutError,
    RateLimitError,
    InternalServerError,
    BadRequestError,
    AuthenticationError,
    PermissionDeniedError)
from tqdm import tqdm
from pathlib import Path
import re


from .caption_generation_prompt import CaptionGenerationPrompt
from .caption_revision_prompt import CaptionRevisionPrompt
from .template_generator import TemplateCaptionGenerator


class CaptionGenerator:
    """Generate radiological captions from lesion metadata using LLM."""

    def __init__(self, use_llm=True):
        """
        Initialize the LLM caption generator.

        Args:
            modality: Imaging modality (e.g., "T1-weighted", "FLAIR")
        """
        self.use_llm = use_llm
        self.model = "gpt-5.4"

        self.generation_prompt = CaptionGenerationPrompt()
        self.revision_prompt = CaptionRevisionPrompt()
        self.template_generator = TemplateCaptionGenerator()
        if use_llm:
            self.client = OpenAI(api_key=os.environ.get("OPENAI_API_KEY"))

    def _build_generation_prompt(self, meta: pd.DataFrame) -> tuple[str, str]:
        return self.generation_prompt.generate(meta, meta.index)

    def _build_revision_prompt(self, meta: pd.DataFrame) -> tuple[str, str]:
        return self.revision_prompt.generate(meta, meta.index)

    def _parse_response(self, response_text: str):
        lines = response_text.strip().split("\n")
        captions = {}
        counter = 0
        for line in lines:
            line = line.strip()
            if line.startswith("CASE"):
                parts = line.split(":")
                captions[int(re.findall(r'\d+', parts[0])[-1])] = (parts[-1].strip())
                counter += 1
            elif line.startswith("Caption"):
                parts = line.split(":")
                captions[int(re.findall(r'\d+', parts[0])[-1])] = (parts[-1].strip())
                counter += 1
            elif line.startswith("Report"):
                report_header, caption = line.split(":", 1)
                captions[int(re.findall(r'\d+', report_header)[-1])] = caption.strip()
                counter += 1

        return captions, counter

    def _generate_fallback(self, meta: pd.DataFrame, index) -> dict:
        generated_dictionary = self.template_generator.generate_caption_from_df(meta)
        return {index: generated_dictionary["detailed"]}

    def prompt_llm(self, system_prompt: str, user_prompt: str,
                   temperature: float = 0.7,
                   max_retries: int = 5, type: str = "generation") -> str:

        if not user_prompt or not user_prompt.strip():
            raise ValueError("User prompt is empty.")
        if not isinstance(temperature, (int, float)) or not (0 <= temperature <= 2):
            raise ValueError("temperature must be a number between 0 and 2.")

        backoff = 1.0
        last_err = None

        # Use structured input so you can include a system message
        input_messages = [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt},
        ]

        for attempt in range(1, max_retries + 1):
            try:
                resp = self.client.responses.create(
                    model=self.model,
                    input=input_messages,
                    reasoning={"effort": "low"},
                    prompt_cache_key=type
                )
                return resp.output_text

            except (RateLimitError, InternalServerError, APIConnectionError, APITimeoutError) as e:
                last_err = e
                if attempt == max_retries:
                    break
                time.sleep(backoff)
                backoff = min(backoff * 2, 20)

            except (AuthenticationError, PermissionDeniedError) as e:
                raise RuntimeError(f"Auth/permission error: {e}") from e

            except BadRequestError as e:
                raise ValueError(f"Bad request: {e}") from e

        raise RuntimeError(f"Failed after {max_retries} attempts. Last error: {last_err}") from last_err

    # SINGLE RETRY VALIDATION ONLY
    def validate_df(self, captions_df, original_df, user_prompt, type):
        if len(captions_df) != len(original_df):
            print("[ERROR] Generated by the following prompt:")
            print(user_prompt)
            missing_indices = original_df.index.difference(captions_df.index)
            if type == "gen":
                missing_df = self.generate_original_caption(original_df.loc[missing_indices], validate=False)
            else:
                missing_df = self.revise_caption(original_df.loc[missing_indices], validate=False)
            if len(missing_df) + len(captions_df) != len(original_df):
                print(f"[ERROR] Error still persists. No longer retrying. Dropping {len(original_df) - len(captions_df) - len(missing_df)} elements")
            captions_df = pd.concat([captions_df, missing_df])
            captions_df = captions_df[~captions_df.index.duplicated(keep="last")]
            return captions_df
        else:
            return captions_df


    def generate_original_caption(self, meta_df: pd.DataFrame, validate:bool = True) -> pd.DataFrame:
        """
        Generate LLM captions from metadata.

        Args:
            meta: pandas Series containing lesion metadata

        Returns:
            Dictionary with llm_caption_1 through llm_caption_4 and path
        """
        system_prompt, user_prompt = self._build_generation_prompt(meta_df)
        number = 0
        try:
            response_text = self.prompt_llm(system_prompt, user_prompt, type="original-caption-generation")
            captions, number = self._parse_response(response_text)
        except Exception as e:
            print(f"LLM caption generation failed: {e}")
            captions = self._generate_fallback(meta_df, meta_df.index)
        captions_df = pd.DataFrame.from_dict(captions, orient='index', columns=['caption'])
        if validate:
            print(f"Supplied {len(meta_df)}, Returned: {number}")
            captions_df = self.validate_df(captions_df, meta_df, user_prompt, type = "gen")
        return captions_df

    def revise_caption(self, unedited_captions: pd.DataFrame, validate:bool = True) -> pd.DataFrame:

        """
        Generate LLM captions from metadata.

        Args:
            meta: pandas Series containing lesion metadata

        Returns:
            Dictionary with llm_caption_1 through llm_caption_4 and path
        """
        system_prompt, user_prompt = self._build_revision_prompt(unedited_captions)
        try:
            response_text = self.prompt_llm(system_prompt, user_prompt, type="revise-created-captions")
            captions, number = self._parse_response(response_text)

        except Exception as e:
            print(f"LLM caption revision failed: {e}")
            return unedited_captions

        captions_df = pd.DataFrame.from_dict(captions, orient='index', columns=['caption'])
        if validate:
            print(f"Supplied {len(unedited_captions)}, Returned: {number}")
            captions_df = self.validate_df(captions_df, unedited_captions, user_prompt, type = "edit")
        return captions_df

    def iter_chunks(self, df: pd.DataFrame, chunk_size: int = 30) -> Generator[pd.DataFrame, Any, None]:
        for start in range(0, len(df), chunk_size):
            yield df.iloc[start:start + chunk_size]

    def save_df(self, df, filepath, name):
        csv_path = Path(filepath) / name
        if csv_path.exists():
            df.to_csv(csv_path, mode='a', header=False, index=False)
        else:
            df.to_csv(csv_path, mode='w', header=True, index=False)

    def resume_captioning(self, meta_df, output_csv):
        if not output_csv.exists():
            return meta_df
        output_df = pd.read_csv(output_csv, index_col=False)
        before = len(meta_df)

        meta_df = meta_df[~meta_df["Brain1_FilePath"].isin(output_df["brain1_file_path"])]

        after = len(meta_df)
        dropped = before - after

        print(f"[INFO] Dropped {dropped} rows based on Brain1_FilePath overlap")

        return meta_df

    def generate_caption(self, meta_df: str, output_path,
                         remove_no_lesion_ratio: float = 0.95,
                         generation_batching: int = 45, revision_batching: int = 75) -> pd.DataFrame:

        meta_df = pd.read_csv(meta_df)
        meta_df = self.resume_captioning(meta_df, Path(output_path) / "captions.csv")
        if not self.use_llm:
            captions = self._generate_fallback(meta_df, meta_df.index)
            return pd.DataFrame.from_dict(captions)

        total_chunks_gen = (len(meta_df) + generation_batching - 1) // generation_batching
        total_chunks_rev = (len(meta_df) + revision_batching - 1) // revision_batching

        unedited_chunks = [self.generate_original_caption(chunk)
                           for chunk in tqdm(self.iter_chunks(meta_df, chunk_size=generation_batching), total=total_chunks_gen,
                                             desc="Generating captions")]
        unedited_df = pd.concat(unedited_chunks)
        self.save_df(unedited_df, output_path, "unedited_captions.csv")

        revised_chunks = [self.revise_caption(chunk)
                          for chunk in tqdm(self.iter_chunks(unedited_df, chunk_size=revision_batching), total=total_chunks_rev,
                                            desc="Revising captions")]
        revised_df = pd.concat(revised_chunks)
        revised_df = self.add_meta(revised_df, meta_df)

        self.save_df(revised_df, output_path, "captions.csv")
        return revised_df

    def review_generation_prompt(self, meta_df: str,):
        print("----------GENERATION PROMPT----------")
        for chunk in (self.iter_chunks(meta_df, chunk_size=30)):
            gen_prompt = self._build_generation_prompt(chunk)
            print(gen_prompt[0])
            print(gen_prompt[1])
            break

    def review_reversion_prompt(self, n_rows=30):
        print("----------REVISION PROMPT----------")

        # Step 1: Create fake indices (simulate real pipeline)
        fake_indices = np.random.choice(range(1000, 9999), size=n_rows, replace=False)

        # Step 2: Create dummy captions (minimal but structured)
        dummy_captions = ["lesion", "normal", "artifact", "unclear", "mass"] * (n_rows // 5 + 1)
        dummy_captions = dummy_captions[:n_rows]

        # Step 3: Build fake unedited captions DataFrame
        unedited_df = pd.DataFrame(
            {"caption": dummy_captions},
            index=fake_indices
        )

        # Step 4: Build revision prompt
        system_prompt, user_prompt = self._build_revision_prompt(unedited_df)

        # Step 5: Print for inspection
        print("----- SYSTEM PROMPT -----")
        print(system_prompt)

        print("\n----- USER PROMPT -----")
        print(user_prompt)

    def add_meta(self, target_df: pd.DataFrame, meta_df: pd.DataFrame) -> pd.DataFrame:
        meta_cols = meta_df[[
            'Brain1_FilePath',
            'Brain2_FilePath',
            'Brain1_LesionSlicePath',
            'Brain2_LesionSlicePath',
            'Brain1_MRIPath',
            'Brain2_MRIPath',
            'Brain1_LesionPath',
            'Brain2_LesionPath',
        ]]
        result = target_df.join(meta_cols, how='inner')
        result = result.rename(columns={
            'Brain1_FilePath': 'brain1_file_path',
            'Brain2_FilePath': 'brain2_file_path',
            'Brain1_LesionSlicePath': 'brain1_lesion_slice_path',
            'Brain2_LesionSlicePath': 'brain2_lesion_slice_path',
            'Brain1_MRIPath': 'brain1_mri_path',
            'Brain2_MRIPath': 'brain2_mri_path',
            'Brain1_LesionPath': 'brain1_lesion_path',
            'Brain2_LesionPath': 'brain2_lesion_path',
        })

        dropped = len(target_df) - len(result)
        if dropped:
            print(f"Warning: {dropped} caption rows dropped due to missing metadata match. This is likely caused by the LLM. If the number is small. It can be ignored.")

        return result